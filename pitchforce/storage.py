"""Private object storage.

The default backend is a private directory on local disk (never served statically; every read goes
through an authorized route). Keys are generated by the application, never taken from user filenames,
so path traversal through an uploaded name is not possible.

An S3-compatible backend can be added by implementing the same small interface.
"""
from __future__ import annotations

import hashlib
import os
import shutil
from pathlib import Path
from typing import BinaryIO, Iterator

from .config import get_settings
from .db import new_id


class StorageError(Exception):
    pass


class LocalStorage:
    def __init__(self, root: Path):
        self.root = root.resolve()
        self.root.mkdir(parents=True, exist_ok=True)

    # -- keys -------------------------------------------------------------
    @staticmethod
    def make_key(prefix: str, ext: str = "") -> str:
        ext = ext.lower()
        if ext and not ext.startswith("."):
            ext = "." + ext
        safe_ext = "".join(c for c in ext if c.isalnum() or c == ".")[:10]
        return f"{prefix.strip('/')}/{new_id()}{safe_ext}"

    def path(self, key: str) -> Path:
        p = (self.root / key).resolve()
        if self.root not in p.parents and p != self.root:
            raise StorageError("Invalid storage key")
        return p

    # -- io ---------------------------------------------------------------
    def put_bytes(self, key: str, data: bytes) -> tuple[int, str]:
        p = self.path(key)
        p.parent.mkdir(parents=True, exist_ok=True)
        tmp = p.with_suffix(p.suffix + ".part")
        tmp.write_bytes(data)
        os.replace(tmp, p)
        return len(data), hashlib.sha256(data).hexdigest()

    def put_file(self, key: str, src: Path, move: bool = False) -> tuple[int, str]:
        p = self.path(key)
        p.parent.mkdir(parents=True, exist_ok=True)
        digest = sha256_file(src)
        size = src.stat().st_size
        if move:
            os.replace(src, p)
        else:
            shutil.copyfile(src, p)
        return size, digest

    def open(self, key: str) -> BinaryIO:
        return open(self.path(key), "rb")

    def read_bytes(self, key: str) -> bytes:
        return self.path(key).read_bytes()

    def exists(self, key: str) -> bool:
        try:
            return self.path(key).exists()
        except StorageError:
            return False

    def size(self, key: str) -> int:
        return self.path(key).stat().st_size

    def delete(self, key: str) -> None:
        try:
            self.path(key).unlink(missing_ok=True)
        except StorageError:
            pass

    def iter_range(self, key: str, start: int, end: int, chunk: int = 1 << 16) -> Iterator[bytes]:
        with self.open(key) as f:
            f.seek(start)
            remaining = end - start + 1
            while remaining > 0:
                data = f.read(min(chunk, remaining))
                if not data:
                    break
                remaining -= len(data)
                yield data

    # -- temp area for chunked uploads -----------------------------------
    def upload_temp_path(self, upload_id: str) -> Path:
        d = self.root / "_uploads"
        d.mkdir(parents=True, exist_ok=True)
        return d / f"{upload_id}.part"


def sha256_file(path: Path) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for block in iter(lambda: f.read(1 << 20), b""):
            h.update(block)
    return h.hexdigest()


_storage: LocalStorage | None = None


def get_storage() -> LocalStorage:
    global _storage
    if _storage is None or _storage.root != get_settings().storage_dir.resolve():
        _storage = LocalStorage(get_settings().storage_dir)
    return _storage
