"""Regenerate the committed example outputs in examples/ from the synthetic SAMPLE event.

    python scripts/generate_examples.py

Uses offline analysis only. Writes report PDF/DOCX, interest workbook, email draft, evidence appendix,
manifest, and the organizer audit workbook for two sample companies. No real data is involved.
"""
from __future__ import annotations

import os
import shutil
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
os.environ.setdefault("DATA_DIR", tempfile.mkdtemp(prefix="pf_examples_"))
os.environ.setdefault("OUTBOUND_FETCH_ENABLED", "false")
os.environ.setdefault("AI_PROVIDER", "offline")


def main() -> None:
    from pitchforce.__main__ import migrate
    from pitchforce.db import SessionLocal
    from pitchforce.jobs.worker import drain
    from pitchforce.models import Artifact, Company
    from pitchforce.reports.package import build_company_package
    from pitchforce.reports.xlsx import audit_workbook
    from pitchforce.services.sample import create_sample_event
    from pitchforce.storage import get_storage

    migrate()
    with SessionLocal() as db:
        ev = create_sample_event(db, None, with_video=False)
        db.commit()
        eid = ev.id
    drain()
    out = ROOT / "examples"
    if out.exists():
        shutil.rmtree(out)
    out.mkdir()
    with SessionLocal() as db:
        from pitchforce.models import Event

        ev = db.get(Event, eid)
        for name in ("Hemaflow Bio", "Brightwell Diagnostics"):
            c = db.query(Company).filter_by(event_id=eid, display_name=name).one()
            build_company_package(db, ev, c)
            db.commit()
            for a in db.query(Artifact).filter_by(company_id=c.id, is_current=True):
                if a.kind in ("company_zip",):
                    continue
                (out / a.filename).write_bytes(get_storage().read_bytes(a.storage_key))
        (out / "SAMPLE_Event_Audit_Workbook.xlsx").write_bytes(audit_workbook(db, ev))
    (out / "README.md").write_text(
        "# Example outputs (synthetic SAMPLE data)\n\n"
        "Generated by `python scripts/generate_examples.py` from the fictional sample event in `pitchforce/sample_data.py`.\n"
        "No real people, companies, scores, or contacts. Video clips are not committed (see tests/test_media.py for real clip tests).\n",
        encoding="utf-8")
    print("Wrote", sorted(p.name for p in out.iterdir()))


if __name__ == "__main__":
    main()
